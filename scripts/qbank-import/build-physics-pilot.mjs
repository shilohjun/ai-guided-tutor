#!/usr/bin/env node
/**
 * Build a small, reviewable pilot bank from the classified physics JSONL.
 *
 * The pilot intentionally keeps the source records separate from the
 * generated 835-question bank so it can be removed or regenerated safely.
 */
import { createReadStream } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { createInterface } from 'node:readline';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const INPUT = join(ROOT, 'Problems', 'physics-by-type', '解答题', 'questions.jsonl');
const OUTPUT = join(ROOT, 'src', 'core', 'qbank-physics-pilot.data.js');
const COUNT = 5;

const selected = [];
const seen = new Set();
const lines = createInterface({
  input: createReadStream(INPUT, { encoding: 'utf8' }),
  crlfDelay: Infinity,
});

for await (const line of lines) {
  if (!line.trim()) continue;
  const record = JSON.parse(line);
  const sourceId = String(record._id ?? record.id ?? '');
  if (seen.has(sourceId)) continue;
  seen.add(sourceId);
  selected.push({
    i: selected.length + 1,
    pilot: true,
    sourceId,
    code: `PHYSICS-PILOT-${String(selected.length + 1).padStart(3, '0')}`,
    no: String(selected.length + 1).padStart(3, '0'),
    ty: '解答题',
    d: record.qs_diff ?? record.difficulty_level ?? '未知',
    p: '导入题库',
    mod: '高中物理',
    chap: '解答题',
    leaf: '计算综合',
    t1: '',
    t2: '',
    src: `导入题库 · 解答题 · ${selected.length + 1}`,
    stemHtml: record.qs_stem ?? record.stem ?? record.html_text ?? '',
    stemText: stripTags(record.qs_stem ?? record.stem ?? record.html_text ?? ''),
    options: [],
    nF: 0,
    nFig: 0,
    knowledgeIds: [],
    methodIds: [],
    answerHtml: record.qs_answer ?? record.answer ?? '',
    answerText: stripTags(record.qs_answer ?? record.answer ?? ''),
    analysisHtml: record.qs_explanation ?? record.explanation ?? '',
    analysisText: stripTags(record.qs_explanation ?? record.explanation ?? ''),
  });
  if (selected.length >= COUNT) break;
}

if (selected.length !== COUNT) {
  throw new Error(`解答题题源不足：需要 ${COUNT} 道，实际只有 ${selected.length} 道`);
}

await mkdir(resolve(OUTPUT, '..'), { recursive: true });
await writeFile(
  OUTPUT,
  `// Generated by scripts/qbank-import/build-physics-pilot.mjs\nexport const PHYSICS_PILOT_SOURCE = ${JSON.stringify(selected)};\n`,
  'utf8',
);
console.log(`已生成 ${selected.length} 道试点题：${OUTPUT}`);

function stripTags(value) {
  return String(value ?? '')
    .replace(/<script\b[^>]*>[\s\S]*?<\/script\s*>/gi, ' ')
    .replace(/<[^>]*>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}
