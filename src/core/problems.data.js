/** 便捷索引 */
export const PROBLEM_BY_ID = new Map(PROBLEMS.map((p) => [p.id, p]));

export function getProblem(id) {
  const p = PROBLEM_BY_ID.get(id);
  if (!p) throw new Error(`未找到题目：${id}`);
  return p;
}

/** 题目总数与全部标准步骤数（评测时算分母） */
export function totalStepCount(problem) {
  return problem.solutionGraphs.reduce((n, g) => n + g.steps.length, 0);
}

/** 下发前端时剥离答案（关键安全约定：参考答案永不出网） */
export function toPublicProblem(problem) {
  return {
    id: problem.id,
    subject: problem.subject,
    topics: problem.topics,
    difficulty: problem.difficulty,
    stem: problem.stem,
    givens: problem.givens,
    asked: problem.asked,
    figure: problem.figure ?? null,
    // 只暴露"有几条路径、各有几步"，不暴露路径内容
    graphSummary: problem.solutionGraphs.map((g) => ({
      id: g.id,
      name: g.name,
      stepCount: g.steps.length,
    })),
    /** 常见错因的"面向学生"表述（教研标签不下发，避免学生反推） */
    conceptTags: [...new Set(problem.solutionGraphs.flatMap((g) => g.steps.flatMap((s) => s.concepts)))],
  };
}
