const knowledge = new Map();
for (const mod of QBANK_GRAPHS.knowledge) for (const chapter of mod.children) for (const leaf of chapter.children) {
  const text = KNOWLEDGE_TEXT[leaf.name] || (leaf.name === '综合应用'
    ? ['',`综合运用${chapter.name}中的基本规律，按对象、阶段与边界条件组织关系。`,'逐一检查各规律的适用条件；不同阶段不能未经验证沿用同一模型。'] : null);
  if (!text) throw new Error(`Missing knowledge description: ${leaf.id} ${leaf.name}`);
  knowledge.set(leaf.id,{id:leaf.id,title:leaf.name === '综合应用' ? `${chapter.name}综合应用` : leaf.name,
    formula:text[0],meaning:text[1],condition:text[2],graphPath:[mod.name,chapter.name,leaf.name]});
}
const methods=new Map();
for (const family of QBANK_GRAPHS.methods) {
  const rootText=METHOD_TEXT[family.id];
  if (rootText) methods.set(family.id,{id:family.id,title:family.name,family:family.name,text:rootText});
  for (const leaf of family.children) {
    const text=METHOD_TEXT[leaf.id];
    if (!text) throw new Error(`Missing method description: ${leaf.id}`);
    methods.set(leaf.id,{id:leaf.id,title:leaf.name,
      family:leaf.id==='t2b' ? '功能关系 · 动能定理' : `${family.name} · ${leaf.name}`,text});
  }
}

export function buildQbankReview(record) {
  const ks=record.knowledgeIds.map(id => knowledge.get(id));
  const ms=record.methodIds.map(id => methods.get(id));
  if (ks.some(x=>!x) || ms.some(x=>!x)) throw new Error(`Incomplete graph mapping for qbank-${record.i}`);
  const focus=ks.slice(0,2).map(k=>k.title).join('、');
  return {source:'qbank-graphs',status:'available',questionCode:record.code,
    knowledge:ks.map(k=>({...k,graphPath:[...k.graphPath]})),
    methods:ms.map(m=>({id:m.id,title:m.title,family:m.family,principle:m.text[0],
      use:`围绕本题的${focus}：${m.text[1]}`,when:m.text[2],boundary:m.text[3]})),
    note:'知识与方法对应原题库标签；说明为配套复习指引，不代表已经掌握，也不替代本题完整解析。'};
}
